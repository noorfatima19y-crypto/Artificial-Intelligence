# Different data types

name = "Ali"          # String
age = 20              # Integer
height = 5.8          # Float
student = True        # Boolean

print("Name:", name)
print("Age:", age)
print("Height:", height)
print("Student:", student)

print("\nname in ",type(name))
print("age  in ",type(age))
print("height in ",type(height))
print("student in ",type(student))


# Special characters

print("\nHello World")        # \n = New line
print("Hello\tWorld")        # \t = Tab space
print("He said \"Hello\"")    # \" = Double quotation mark
print("C:\\Python")           # \\ = Backslash